RUNTIMES: tuple[VendoredRuntime, ...] = (THREEJS, PLOTLY)


def _sha256(path: Path) -> str:
    """
    Return the SHA-256 hex digest of a file.

    Parameters
    ----------
    path : Path
        File to hash.

    Returns
    -------
    str
        The hex digest.
    """
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _license_text(runtime: VendoredRuntime) -> str:
    """
    Render the ``LICENSES.md`` content for a vendored runtime.

    Parameters
    ----------
    runtime : VendoredRuntime
        The runtime whose vendored files to document.

    Returns
    -------
    str
        The full markdown content.
    """
    rows = '\n'.join(f'| `{asset.filename}` | `{asset.url}` |' for asset in runtime.assets)
    return (
        f'# Vendored {runtime.name}\n\n'
        f'Pinned, bundled snapshot fetched verbatim from jsDelivr '
        f'(npm `{runtime.package}@{runtime.version}`). Generated by '
        f'`tools/bump_vendored_js.py`; do not edit by hand — replace only '
        f'by re-fetching the pinned version with `pixi run vendor-update-js`.\n\n'
        f'| File | Source URL |\n| --- | --- |\n{rows}\n\n'
        f'**Version:** {runtime.version}.\n\n'
        f'**Licence:** {runtime.licence}\n\n'
        f'These are upstream snapshots, not project-owned code: they are '
        f'excluded from linting, formatting, coverage, and test-structure '
        f'mirroring in `pyproject.toml`.\n'
    )


def _bump_runtime(runtime: VendoredRuntime) -> None:
    """
    Fetch a runtime's assets and regenerate its ``LICENSES.md``.

    Parameters
    ----------
    runtime : VendoredRuntime
        The runtime to fetch and write.
    """
    dest_dir = _REPO_ROOT / runtime.dest_dir
    dest_dir.mkdir(parents=True, exist_ok=True)
    for asset in runtime.assets:
        fetched = pooch.retrieve(
            url=asset.url,
            known_hash=f'sha256:{asset.sha256}',
            fname=asset.filename,
            path=_CACHE_DIR,
        )
        shutil.copy2(fetched, dest_dir / asset.filename)
        print(f'  wrote {runtime.dest_dir / asset.filename}')
    (dest_dir / 'LICENSES.md').write_text(_license_text(runtime), encoding='utf-8')
    print(f'  wrote {runtime.dest_dir / "LICENSES.md"}')


def _check_runtime(runtime: VendoredRuntime) -> list[str]:
    """
    Return drift messages for a runtime's vendored files.

    Parameters
    ----------
    runtime : VendoredRuntime
        The runtime to verify.

    Returns
    -------
    list[str]
        One message per missing or mismatched file; empty when clean.
    """
    problems: list[str] = []
    dest_dir = _REPO_ROOT / runtime.dest_dir
    for asset in runtime.assets:
        path = dest_dir / asset.filename
        if not path.is_file():
            problems.append(f'missing: {runtime.dest_dir / asset.filename}')
            continue
        actual = _sha256(path)
        if actual != asset.sha256:
            problems.append(
                f'hash drift: {runtime.dest_dir / asset.filename} '
                f'(expected {asset.sha256}, actual {actual})'
            )
    return problems


def bump() -> int:
    """
    Fetch and write every pinned runtime.

    Returns
    -------
    int
        Process exit code (always ``0``; integrity failures raise).
    """
    for runtime in RUNTIMES:
        print(f'{runtime.name} {runtime.version}:')
        _bump_runtime(runtime)
    print('Done. Stage and commit the refreshed vendored files.')
    return 0


def check() -> int:
    """
    Verify vendored files match the pinned hashes.

    Returns
    -------
    int
        ``0`` when every file matches, ``1`` on any drift.
    """
    problems: list[str] = []
    for runtime in RUNTIMES:
        problems.extend(_check_runtime(runtime))
    if problems:
        print('Vendored JS drift detected:')
        for problem in problems:
            print(f'  {problem}')
        return 1
    print('Vendored JS matches the pinned table.')
    return 0


def main() -> int:
    """
    Parse arguments and run the bump or check workflow.

    Returns
    -------
    int
        Process exit code.
    """
    parser = argparse.ArgumentParser(description='Bump or verify vendored JS runtimes.')
    parser.add_argument(
        '--check',
        action='store_true',
        help='Verify vendored files against the pinned hashes (no network, no writes).',
    )
    args = parser.parse_args()
    return check() if args.check else bump()


if __name__ == '__main__':
    sys.exit(main())
