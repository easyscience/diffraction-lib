"""
Bump or verify the vendored JavaScript runtimes.

Fetches the pinned Plotly and Three.js assets from jsDelivr with
integrity checks, writes them into their canonical vendor folders, and
regenerates each folder's ``LICENSES.md``. With ``--check`` it re-hashes
the already-vendored files against the pinned table and writes nothing
(a CI drift guard); no network access is used in that mode.

The pinned table below is the single source of truth for the vendored
runtime versions. To bump a runtime: change its ``version``, the asset
URLs, and the expected ``sha256`` hashes, then run
``pixi run vendor-update-js``.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

import pooch

_REPO_ROOT = Path(__file__).resolve().parent.parent
_CACHE_DIR = Path.home() / '.cache' / 'easydiffraction-vendored-js'


@dataclass(frozen=True)
class VendoredAsset:
    """One vendored file: its name, source URL, and expected hash."""

    filename: str
    url: str
    sha256: str


@dataclass(frozen=True)
class VendoredRuntime:
    """A pinned runtime vendored as one or more files in one folder."""

    name: str
    package: str
    version: str
    dest_dir: Path
    licence: str
    assets: tuple[VendoredAsset, ...]


